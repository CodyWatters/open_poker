"""Generate pokerapp/preflop_data.py: 169 starting-hand classes ranked best to worst.
Score = normalized equity vs 1 random hand + vs 2 random hands (rewards multiway playability)."""
import random, sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from pokerapp.cards import evaluate, hand_class, RANKS

def equity(hole, nopp, n, rng):
    dead = set(hole); deck = [c for c in range(52) if c not in dead]; w = 0.0
    for _ in range(n):
        s = rng.sample(deck, 5 + 2 * nopp); board = s[:5]
        h = evaluate(hole + board); best = 0; ties = 0
        for i in range(nopp):
            v = evaluate(s[5 + 2*i:7 + 2*i] + board)
            if v > best: best, ties = v, 1
            elif v == best: ties += 1
        if h > best: w += 1
        elif h == best: w += 1.0 / (ties + 1)
    return w / n

rng = random.Random(7); reps = {}
for a in range(52):
    for b in range(a):
        reps.setdefault(hand_class([a, b]), [a, b])
N = int(sys.argv[1]) if len(sys.argv) > 1 else 6000
scores = {k: equity(v, 1, N, rng) / 0.5 + equity(v, 2, N, rng) / 0.3333 for k, v in reps.items()}
order = sorted(scores, key=lambda k: -scores[k])
out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "pokerapp", "preflop_data.py")
with open(out, "w") as f:
    f.write('"""Generated by tools/gen_preflop.py. 169 hand classes, strongest first."""\n')
    f.write("ORDER = " + repr(order) + "\n")
print(order[:30]); print(order[-10:])
